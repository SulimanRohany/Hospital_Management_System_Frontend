export function translateText(value, language) {
  if (!value || language === "en") return value;
  const leading = value.match(/^\s*/)?.[0] || "";
  const trailing = value.match(/\s*$/)?.[0] || "";
  const text = value.trim();
  if (!text) return value;
  const exact = findExactTranslation(text, language);
  if (exact) return `${leading}${exact}${trailing}`;

  // React often splits a sentence around a dynamic value, leaving punctuation
  // attached to the static text node (for example "Good day, {name}").
  const punctuated = text.match(/^(.*?)(\.{1,3}|[…,:;!?،؛؟])$/);
  if (punctuated) {
    const localized = findExactTranslation(punctuated[1], language);
    if (localized) return `${leading}${localized}${punctuated[2]}${trailing}`;
  }

  for (const [pattern, format] of dynamicTranslations[language] || []) {
    const match = text.match(pattern);
    if (match) return `${leading}${format(...match)}${trailing}`;
  }

  // Keeping an untranslated phrase intact is safer than showing a misleading,
  // grammatically broken clinical or financial instruction.
  return value;
}

function translateDom(root, language, originals) {
  if (!root || root.nodeType !== Node.ELEMENT_NODE) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  if (root.firstChild?.nodeType === Node.TEXT_NODE) nodes.unshift(root.firstChild);

  for (const node of new Set(nodes)) {
    if (node.parentElement?.closest("[data-no-translate]") || ["SCRIPT", "STYLE"].includes(node.parentElement?.tagName)) continue;
    const original = originals.text.get(node) ?? node.nodeValue;
    originals.text.set(node, original);
    const next = translateText(original, language);
    if (node.nodeValue !== next) node.nodeValue = next;
  }

  const elements = [root, ...root.querySelectorAll("[placeholder], [aria-label], [title]")];
  for (const element of elements) {
    for (const attribute of ["placeholder", "aria-label", "title"]) {
      if (!element.hasAttribute?.(attribute) || element.closest("[data-no-translate]")) continue;
      let values = originals.attributes.get(element);
      if (!values) { values = {}; originals.attributes.set(element, values); }
      values[attribute] ??= element.getAttribute(attribute);
      const next = translateText(values[attribute], language);
      if (element.getAttribute(attribute) !== next) element.setAttribute(attribute, next);
    }
  }
}

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState("en");
  const [ready, setReady] = useState(false);
  const originals = useRef({ text: new WeakMap(), attributes: new WeakMap() });

  useEffect(() => {
    const timer = window.setTimeout(() => {
      const saved = localStorage.getItem(STORAGE_KEY);
      const browserLanguage = navigator.language?.toLowerCase();
      const preferred = saved && LANGUAGES[saved] ? saved : browserLanguage?.startsWith("ps") ? "ps" : browserLanguage?.startsWith("fa") ? "fa" : "en";
      document.documentElement.lang = preferred;
      document.documentElement.dir = LANGUAGES[preferred].direction;
      setLanguageState(preferred);
      setReady(true);
    }, 0);
    return () => window.clearTimeout(timer);
  }, []);

  const setLanguage = useCallback((next) => {
    if (!LANGUAGES[next]) return;
    localStorage.setItem(STORAGE_KEY, next);
    document.documentElement.lang = next;
    document.documentElement.dir = LANGUAGES[next].direction;
    setLanguageState(next);
  }, []);

  useEffect(() => {
    if (!ready) return;
    const config = LANGUAGES[language];
    document.documentElement.lang = language;
    document.documentElement.dir = config.direction;
    document.body.dataset.language = language;
    let translating = false;
    const apply = (target = document.body) => {
      if (translating) return;
      translating = true;
      translateDom(target.nodeType === Node.ELEMENT_NODE ? target : target.parentElement, language, originals.current);
      translating = false;
    };
    apply();
    const observer = new MutationObserver((mutations) => {
      if (translating) return;
      for (const mutation of mutations) {
        if (mutation.type === "characterData") {
          const original = originals.current.text.get(mutation.target);
          if (original !== undefined && mutation.target.nodeValue !== translateText(original, language)) {
            originals.current.text.set(mutation.target, mutation.target.nodeValue);
          }
          apply(mutation.target.parentElement);
        }
        if (mutation.type === "attributes") {
          const values = originals.current.attributes.get(mutation.target);
          const original = values?.[mutation.attributeName];
          if (original !== undefined && mutation.target.getAttribute(mutation.attributeName) !== translateText(original, language)) {
            values[mutation.attributeName] = mutation.target.getAttribute(mutation.attributeName);
          }
          apply(mutation.target);
        }
        for (const node of mutation.addedNodes) {
          if (node.nodeType === Node.ELEMENT_NODE) apply(node);
          if (node.nodeType === Node.TEXT_NODE && node.parentElement) apply(node.parentElement);
        }
      }
    });
    observer.observe(document.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ["placeholder", "aria-label", "title"] });
    return () => observer.disconnect();
  }, [language, ready]);

  const t = useCallback((text) => translateText(text, language), [language]);
  const value = useMemo(() => ({ language, setLanguage, direction: LANGUAGES[language].direction, t }), [language, setLanguage, t]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error("useLanguage must be used inside LanguageProvider");
  return context;
}

